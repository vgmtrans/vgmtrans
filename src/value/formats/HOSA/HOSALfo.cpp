LfoShape vibratoShape(u8 waveform) {
  switch (waveform & 0x0f) {
    case 0: return sampled(LfoWaveform::Square, kRampedSquare);
    case 1: return sampled(LfoWaveform::Square, kSquare);
    case 2: return sampled(LfoWaveform::Square, kRampedPositivePulse);
    case 3: return sampled(LfoWaveform::Square, kPositivePulse);
    case 4: return sampled(LfoWaveform::Square, kRampedNegativePulse);
    case 5: return sampled(LfoWaveform::Square, kNegativePulse);
    case 6: return ramped(LfoWaveform::Sine, kSine39);
    case 7: return sampled(LfoWaveform::Sine, kSine39);
    case 8: return ramped(LfoWaveform::Triangle, kTriangle);
    case 9: return sampled(LfoWaveform::Triangle, kTriangle);
    case 10: return ramped(LfoWaveform::Sine, kSine20);
    case 11: return sampled(LfoWaveform::Sine, kSine20);
    case 12: return sampled(LfoWaveform::Noise, kNoise);
    case 13: return sampled(LfoWaveform::Noise, kNegativeNoise);
    case 14: return ramped(LfoWaveform::Sine, kSine10);
    default: return sampled(LfoWaveform::Sine, kSine10);
  }
}

