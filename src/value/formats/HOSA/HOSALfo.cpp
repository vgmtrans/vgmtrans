[[nodiscard]] LfoShape sampled(LfoWaveform waveform, std::span<const s16> table) {
  LfoShape shape{.waveform = waveform};
  shape.samples.reserve(table.size());
  for (const s16 sample : table) shape.samples.push_back(sample / kTableScale);
  return shape;
}

[[nodiscard]] LfoShape ramped(LfoWaveform waveform, std::span<const s16> table) {
  LfoShape shape{.waveform = waveform};
  shape.samples.reserve(table.size() * 4);
  for (int amplitude = 1; amplitude <= 4; ++amplitude) {
    for (const s16 sample : table) shape.samples.push_back((sample * amplitude / 4) / kTableScale);
  }
  return shape;
}

